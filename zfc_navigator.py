def compose_formula(entry: dict) -> List[int]:
    """
    Compose a full ZFC formula token sequence for a grammar tuple.

    Structure: BOS + [prim_template + SEP_PRIM] × 12 + EOS
    Each primitive contributes its canonical ZFC fragment, separated by
    SEP_PRIM markers so the encoder can attend across primitive boundaries.

    Returns a list of token indices (integers).
    """
    tokens = [BOS_IDX]
    for prim in PRIMITIVES:
        val  = entry[prim]
        frag = ZFC_TEMPLATES[prim][val]
        tokens.extend(TOKEN2IDX[t] for t in frag)
        tokens.append(SEP_IDX)
    tokens.append(EOS_IDX)
    return tokens


def pad_formula(tokens: List[int], max_len: int = 256) -> List[int]:
    """Truncate or right-pad a token sequence to max_len."""
    if len(tokens) >= max_len:
        return tokens[:max_len - 1] + [EOS_IDX]
    return tokens + [PAD_IDX] * (max_len - len(tokens))


# ── 4. ZFC Encoder (formula tokens → primitive logits) ──────────────────────
#
# K_slow architecture: 4-layer Transformer encoder with CLS token.
# Reads the full formula simultaneously — no sequential bottleneck.
# 12 classification heads, one per primitive, each predicting the ordinal value.

class ZFCEncoder(nn.Module):
    """
    Transformer encoder: ZFC token sequence → 12 primitive class logits.

    Each head i outputs logits over NUM_VALUES[PRIMITIVES[i]] classes.
    The predicted primitive value is argmax of the corresponding head.
    """

    def __init__(
        self,
        vocab_size:  int = ZFC_VOCAB_SIZE,
        max_len:     int = 256,       # G_aleph: maximize context
        hidden_dim:  int = 256,       # K_slow + F_hbar: same as other navigators
        n_heads:     int = 4,         # G_aleph: 4 attention heads
        n_layers:    int = 4,         # K_slow: deep global integration
        dropout:     float = 0.1,
    ):
        super().__init__()
        self.hidden_dim = hidden_dim

        # Token + position embeddings
        self.tok_emb = nn.Embedding(vocab_size, hidden_dim, padding_idx=PAD_IDX)
        self.pos_emb = nn.Embedding(max_len, hidden_dim)

        # K_slow: Transformer encoder layers (global self-attention)
        enc_layer = nn.TransformerEncoderLayer(
            d_model=hidden_dim,
            nhead=n_heads,
            dim_feedforward=hidden_dim * 4,
            dropout=dropout,
            batch_first=True,
            norm_first=True,           # pre-norm for stability
        )
        self.transformer = nn.TransformerEncoder(enc_layer, num_layers=n_layers)

        # 12 classification heads — one per primitive
        self.heads = nn.ModuleList([
            nn.Linear(hidden_dim, NUM_VALUES[p])
            for p in PRIMITIVES
        ])

        self.dropout = nn.Dropout(dropout)
        self._init_weights()

    def _init_weights(self):
        nn.init.normal_(self.tok_emb.weight, std=0.02)
        nn.init.normal_(self.pos_emb.weight, std=0.02)
        for h in self.heads:
            nn.init.xavier_uniform_(h.weight)

    def forward(self, token_ids: torch.Tensor) -> List[torch.Tensor]:
        """
        Args:
            token_ids: (B, L) integer token indices
        Returns:
            List of 12 tensors, each (B, num_values[i]) — logits per primitive
        """
        B, L = token_ids.shape
        positions = torch.arange(L, device=token_ids.device).unsqueeze(0)
        pad_mask  = (token_ids == PAD_IDX)               # (B, L) bool

        x = self.dropout(self.tok_emb(token_ids) + self.pos_emb(positions))
        x = self.transformer(x, src_key_padding_mask=pad_mask)   # (B, L, H)

        # CLS representation: mean over non-padding tokens (G_aleph: use all)
        lens = (~pad_mask).float().sum(dim=1, keepdim=True).clamp(min=1)
        x_mean = (x * (~pad_mask).float().unsqueeze(-1)).sum(1) / lens  # (B, H)

        return [head(x_mean) for head in self.heads]


# ── 5. Roundtrip (Frobenius) loss ────────────────────────────────────────────
#
# P_pm_sym mandate: μ∘δ = id.  Here:
#   μ = compose_formula   (tuple → ZFC tokens)
#   δ = ZFCEncoder        (ZFC tokens → predicted tuple)
#
# L_frob = mean cross-entropy over 12 primitives between
#          predicted class and true class.
#
# The per-primitive contribution exposes which primitives are non-transmissible.

def frobenius_loss(
    logits_list: List[torch.Tensor],   # 12 tensors (B, num_values[i])
    targets:     torch.Tensor,         # (B, 12) integer targets
) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Returns:
        total_loss: scalar mean cross-entropy
        per_prim:   (12,) tensor of per-primitive losses (for probe analysis)
    """
    losses = []
    for i, logits in enumerate(logits_list):
        ce = F.cross_entropy(logits, targets[:, i])
        losses.append(ce)
    per_prim = torch.stack(losses)
    return per_prim.mean(), per_prim


# ── 6. Dataset preparation ───────────────────────────────────────────────────

def load_catalog(path: str = None) -> List[dict]:
    """
    Load catalog entries, delegating to imscrbgrmr.registry.load_catalog_dicts().

    Reads from (priority order, first-occurrence-wins deduplication):
      1. ~/.imscrbgrmr/catalog.json  (live CLI registry — entries added via
         `imscribe generate` / `imscribe encode`)
      2. <project_root>/syncon_catalog*.json  (committed catalog)
      3. `path` if provided (single file or glob pattern)

    path can be:
      - a single file path (str)
      - a glob pattern (str containing '*')
      - None  → use canonical sources only
    """
    try:
        from imscrbgrmr.registry import load_catalog_dicts
        return load_catalog_dicts(extra_path=path)
    except ImportError:
        # Fallback for isolated runs without the package installed
        import glob as _glob
        _DEFAULT_CATALOG_GLOB = "syncon_catalog*.json"
        if path is None:
            paths = sorted(_glob.glob(_DEFAULT_CATALOG_GLOB))
            if not paths:
                raise FileNotFoundError(
                    f"No files matching '{_DEFAULT_CATALOG_GLOB}' found. "
                    "Pass --catalog to specify a path."
                )
        elif "*" in str(path) or "?" in str(path):
            paths = sorted(_glob.glob(path))
            if not paths:
                raise FileNotFoundError(f"No files matching '{path}' found.")
        else:
            paths = [path]
        seen_names: set = set()
        merged: List[dict] = []
        for p in paths:
            with open(p) as f:
                entries = json.load(f)
            for e in entries:
                name = e.get("name", "")
                if name not in seen_names:
                    seen_names.add(name)
                    merged.append(e)
        return merged


def build_dataset(
    catalog: List[dict],
    max_len: int = 256,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Returns:
        token_seqs: (N, max_len) int64 tensor
        targets:    (N, 12) int64 tensor of true primitive ordinal indices
    """
    token_list  = []
    target_list = []
    for entry in catalog:
        # Skip entries missing any primitive
        if not all(p in entry and entry[p] in ORDINALS[p] for p in PRIMITIVES):
            continue
        tokens  = pad_formula(compose_formula(entry), max_len)
        indices = tuple_to_indices(entry)
        token_list.append(tokens)
        target_list.append(indices)

    token_seqs = torch.tensor(token_list,  dtype=torch.long)
    targets    = torch.tensor(target_list, dtype=torch.long)
    return token_seqs, targets


# ── 7. Training ──────────────────────────────────────────────────────────────

def train(
    catalog_path: str   = None,
    n_epochs:     int   = 300,        # K_slow + H_inf: integrative dynamics need time
    batch_size:   int   = 64,         # G_aleph: large batch for global statistics
    lr:           float = 3e-4,       # K_slow + F_hbar: careful optimisation
    hidden_dim:   int   = 256,
    n_layers:     int   = 4,          # K_slow: 4 Transformer layers
    max_len:      int   = 256,        # G_aleph: maximise context window
    seed:         int   = 42,
    save_path:    str   = "zfc_encoder.pt",
):
    torch.manual_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[zfc_navigator] device={device}  vocab={ZFC_VOCAB_SIZE}  max_len={max_len}")

    catalog = load_catalog(catalog_path)
    token_seqs, targets = build_dataset(catalog, max_len)
    print(f"[zfc_navigator] dataset: {len(token_seqs)} valid entries ({len(catalog)} loaded)")

    # Check decoherence instances in the dataset
    n_fhbar    = sum(1 for e in catalog if e.get("F") == "F_hbar")
    n_todot    = sum(1 for e in catalog if e.get("T") == "T_odot")
    n_dodot    = sum(1 for e in catalog if e.get("D") == "D_odot")
    n_gseq     = sum(1 for e in catalog if e.get("Gamma") == "G_seq")
    print(f"[zfc_navigator] non-transmissible instances:")
    print(f"  F_hbar  (total collapse):   {n_fhbar}")
    print(f"  T_odot  (partial collapse): {n_todot}")
    print(f"  D_odot  (partial collapse): {n_dodot}")
    print(f"  G_seq   (partial collapse): {n_gseq}")

    dataset    = TensorDataset(token_seqs, targets)
    loader     = DataLoader(dataset, batch_size=batch_size, shuffle=True)

    model      = ZFCEncoder(hidden_dim=hidden_dim, n_layers=n_layers, max_len=max_len).to(device)
    optimiser  = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler  = torch.optim.lr_scheduler.CosineAnnealingLR(optimiser, T_max=n_epochs)

    n_params = sum(p.numel() for p in model.parameters())
    print(f"[zfc_navigator] encoder parameters: {n_params:,}")

    best_loss = float("inf")
    for epoch in range(1, n_epochs + 1):
        model.train()
        epoch_loss = 0.0
        epoch_prim = torch.zeros(12)
        n_batches  = 0

        for toks, tgts in loader:
            toks, tgts = toks.to(device), tgts.to(device)
            optimiser.zero_grad()
            logits    = model(toks)
            loss, pp  = frobenius_loss(logits, tgts)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimiser.step()
            epoch_loss += loss.item()
            epoch_prim += pp.detach().cpu()
            n_batches  += 1

        scheduler.step()
        avg_loss  = epoch_loss / n_batches
        avg_prim  = epoch_prim / n_batches

        if epoch % 50 == 0 or epoch == 1:
            # Show the two highest-loss primitives (likely F and T/D for non-transmissibles)
            top2 = avg_prim.topk(2)
            p1   = PRIMITIVES[top2.indices[0]]
            p2   = PRIMITIVES[top2.indices[1]]
            print(
                f"  ep {epoch:4d}  loss={avg_loss:.4f}  "
                f"top-loss-prims: {p1}={top2.values[0]:.3f}  {p2}={top2.values[1]:.3f}"
            )

        if avg_loss < best_loss:
            best_loss = avg_loss
            torch.save(model.state_dict(), save_path)

    print(f"[zfc_navigator] training complete. best loss={best_loss:.4f}  saved → {save_path}")
    return model


# ── 8. Transmissibility Probe ────────────────────────────────────────────────
#
# For each catalog entry:
#   1. Compose the ZFC formula from the tuple
#   2. Run through the encoder
#   3. Compare predicted tuple to input tuple
#   4. Compute:
#      - roundtrip_loss: mean cross-entropy (from frobenius_loss)
#      - roundtrip_dist: grammar distance between predicted and input tuple
#      - per_prim_loss:  which primitives contribute most
#      - collapse_flags: which non-transmissible values are present
#
# The roundtrip_dist is the key measure: it should be ≥ d(tuple, T_ZFC).
# For IUG-type entries (F_hbar, T_odot, D_odot, G_seq), the floor is predictable
# from the IUG_NON_TRANSMISSIBILITY analysis.

@dataclass
class ProbeResult:
    name:            str
    input_tuple:     dict
    predicted_tuple: dict
    roundtrip_dist:  float
    roundtrip_loss:  float
    per_prim_loss:   Dict[str, float]
    collapses:       List[str]    # which primitives collapsed


def run_probe(
    catalog_path: str  = None,
    model_path:   str  = "zfc_encoder.pt",
    max_len:      int  = 256,
    top_n:        int  = 20,
    hidden_dim:   int  = 256,
    n_layers:     int  = 4,
):
    device  = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    catalog = load_catalog(catalog_path)

    model = ZFCEncoder(hidden_dim=hidden_dim, n_layers=n_layers, max_len=max_len).to(device)
    model.load_state_dict(torch.load(model_path, map_location=device))
    model.eval()

    results: List[ProbeResult] = []

    with torch.no_grad():
        for entry in catalog:
            if not all(p in entry and entry[p] in ORDINALS[p] for p in PRIMITIVES):
                continue

            tokens  = torch.tensor(
                [pad_formula(compose_formula(entry), max_len)],
                dtype=torch.long, device=device,
            )
            targets = torch.tensor(
                [tuple_to_indices(entry)],
                dtype=torch.long, device=device,
            )

            logits       = model(tokens)
            loss, pp     = frobenius_loss(logits, targets)

            # Predicted tuple
            pred_indices = [int(logits[i].argmax(dim=-1).item()) for i in range(12)]
            pred_tuple   = indices_to_tuple(pred_indices)

            rt_dist = tuple_distance(entry, pred_tuple)

            per_prim = {PRIMITIVES[i]: float(pp[i]) for i in range(12)}

            # Flag collapse events
            collapses = []
            COLLAPSE_MAP = {
                "F":     ("F_hbar",  "F_ell",   "total"),
                "T":     ("T_odot",  "T_in",    "partial"),
                "D":     ("D_odot",  "D_infty", "partial"),
                "Gamma": ("G_seq",   "G_and",   "residual"),
            }
            for prim, (bad_val, zfc_val, kind) in COLLAPSE_MAP.items():
                if entry.get(prim) == bad_val:
                    predicted = pred_tuple.get(prim, "?")
                    collapses.append(
                        f"{prim}: {bad_val}→{predicted} ({kind})"
                    )
            # Inverse F collapse: F_ell hallucinated as F_hbar
            if entry.get("F") == "F_ell" and pred_tuple.get("F") == "F_hbar":
                collapses.append("F: F_ell→F_hbar (hallucination)")

            results.append(ProbeResult(
                name            = entry.get("name", "?"),
                input_tuple     = {p: entry[p] for p in PRIMITIVES},
                predicted_tuple = pred_tuple,
                roundtrip_dist  = rt_dist,
                roundtrip_loss  = float(loss),
                per_prim_loss   = per_prim,
                collapses       = collapses,
            ))

    results.sort(key=lambda r: r.roundtrip_dist, reverse=True)

    print("\n" + "=" * 80)
    print("TRANSMISSIBILITY PROBE — Top entries by roundtrip distance")
    print("=" * 80)
    print(f"{'Name':<35} {'d_rt':>6}  {'loss':>6}  Collapses")
    print("-" * 80)
    for r in results[:top_n]:
        col_str = "; ".join(r.collapses) if r.collapses else "—"
        print(f"{r.name[:35]:<35} {r.roundtrip_dist:>6.3f}  {r.roundtrip_loss:>6.3f}  {col_str}")

    # Summary statistics
    print("\n" + "─" * 80)
    all_dists = [r.roundtrip_dist for r in results]
    fhbar_dists = [r.roundtrip_dist for r in results
                   if r.input_tuple.get("F") == "F_hbar"]
    todot_dists = [r.roundtrip_dist for r in results
                   if r.input_tuple.get("T") == "T_odot"]
    zfc_ref     = [r for r in results
                   if r.name in ("zfc", "ZFC", "zfc_foundations", "set_theory_zfc")]

    print(f"Total entries probed:       {len(results)}")
    print(f"Mean roundtrip distance:    {np.mean(all_dists):.4f}")
    print(f"Max roundtrip distance:     {np.max(all_dists):.4f}")
    if fhbar_dists:
        print(f"F_hbar entries ({len(fhbar_dists)}):       "
              f"mean d_rt = {np.mean(fhbar_dists):.4f}  "
              f"(predicted floor ≥ 2.0 from F decoherence)")
    if todot_dists:
        print(f"T_odot entries ({len(todot_dists)}):       "
              f"mean d_rt = {np.mean(todot_dists):.4f}")
    if zfc_ref:
        print(f"ZFC self-probe:             d_rt = {zfc_ref[0].roundtrip_dist:.4f}  "
              f"(should be ≈ 0)")

    # Per-primitive mean loss
    print("\nMean per-primitive roundtrip loss (higher = harder to transmit):")
    prim_means = {
        p: np.mean([r.per_prim_loss[p] for r in results])
        for p in PRIMITIVES
    }
    for p, v in sorted(prim_means.items(), key=lambda x: -x[1]):
        bar = "█" * int(v * 20)
        print(f"  {p:<6}  {v:.4f}  {bar}")

    return results


