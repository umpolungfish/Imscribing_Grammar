def render_tokens(token_names: List[str]) -> str:
    """
    Convert a list of token name strings to a readable mathematical expression.
    Tight-packs parens; spaces around quantifiers/connectives/relations.
    """
    parts = []
    for t in token_names:
        sym = _TM.get(t, t)
        if not sym:
            continue
        if t in ("LPAREN", "RPAREN", "COMMA", "DOT"):
            parts.append(sym)
        else:
            parts.append(f" {sym}")
    raw = "".join(parts).strip()
    # Collapse multiple spaces
    import re
    return re.sub(r"  +", " ", raw)


