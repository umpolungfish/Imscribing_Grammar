def compose_formula(entry: dict) -> List[int]:
    """
    Compose a full ZFC formula token sequence for a grammar tuple.

    Structure: BOS + [prim_template + SEP_PRIM] × 12 + EOS
    Each primitive contributes its canonical ZFC fragment, separated by
    SEP_PRIM markers so the encoder can attend across primitive boundaries.

    Returns a list of token indices (integers).
    """
    tokens = [BOS_IDX]
    for prim in PRIMITIVES:
        val  = entry[prim]
        frag = ZFC_TEMPLATES[prim][val]
        tokens.extend(TOKEN2IDX[t] for t in frag)
        tokens.append(SEP_IDX)
    tokens.append(EOS_IDX)
    return tokens


def pad_formula(tokens: List[int], max_len: int = 256) -> List[int]:
    """Truncate or right-pad a token sequence to max_len."""
    if len(tokens) >= max_len:
        return tokens[:max_len - 1] + [EOS_IDX]
    return tokens + [PAD_IDX] * (max_len - len(tokens))


# ── 4. ZFC Encoder (formula tokens → primitive logits) ──────────────────────
#
# Ç_@ architecture: 4-layer Transformer encoder with CLS token.
# Reads the full formula simultaneously — no sequential bottleneck.
# 12 classification heads, one per primitive, each predicting the ordinal value.

class ZFCEncoder(nn.Module):
    """
    Transformer encoder: ZFC token sequence → 12 primitive class logits.

    Each head i outputs logits over NUM_VALUES[PRIMITIVES[i]] classes.
    The predicted primitive value is argmax of the corresponding head.
    """

    def __init__(
        self,
        vocab_size:  int = ZFC_VOCAB_SIZE,
        max_len:     int = 256,       # Γ_ʔ: maximize context
        hidden_dim:  int = 256,       # Ç_@ + ƒ_ż: same as other navigators
        n_heads:     int = 4,         # Γ_ʔ: 4 attention heads
        n_layers:    int = 4,         # Ç_@: deep global integration
        dropout:     float = 0.1,
    ):
        super().__init__()
        self.hidden_dim = hidden_dim

        # Token + position embeddings
        self.tok_emb = nn.Embedding(vocab_size, hidden_dim, padding_idx=PAD_IDX)
        self.pos_emb = nn.Embedding(max_len, hidden_dim)

        # Ç_@: Transformer encoder layers (global self-attention)
        enc_layer = nn.TransformerEncoderLayer(
            d_model=hidden_dim,
            nhead=n_heads,
            dim_feedforward=hidden_dim * 4,
            dropout=dropout,
            batch_first=True,
            norm_first=True,           # pre-norm for stability
        )
        self.transformer = nn.TransformerEncoder(enc_layer, num_layers=n_layers)

        # 12 classification heads — one per primitive
        self.heads = nn.ModuleList([
            nn.Linear(hidden_dim, NUM_VALUES[p])
            for p in PRIMITIVES
        ])

        self.dropout = nn.Dropout(dropout)
        self._init_weights()

    def _init_weights(self):
        nn.init.normal_(self.tok_emb.weight, std=0.02)
        nn.init.normal_(self.pos_emb.weight, std=0.02)
        for h in self.heads:
            nn.init.xavier_uniform_(h.weight)

    def forward(self, token_ids: torch.Tensor) -> List[torch.Tensor]:
        """
        Args:
            token_ids: (B, L) integer token indices
        Returns:
            List of 12 tensors, each (B, num_values[i]) — logits per primitive
        """
        B, L = token_ids.shape
        positions = torch.arange(L, device=token_ids.device).unsqueeze(0)
        pad_mask  = (token_ids == PAD_IDX)               # (B, L) bool

        x = self.dropout(self.tok_emb(token_ids) + self.pos_emb(positions))
        x = self.transformer(x, src_key_padding_mask=pad_mask)   # (B, L, H)

        # CLS representation: mean over non-padding tokens (Γ_ʔ: use all)
        lens = (~pad_mask).float().sum(dim=1, keepdim=True).clamp(min=1)
        x_mean = (x * (~pad_mask).float().unsqueeze(-1)).sum(1) / lens  # (B, H)

        return [head(x_mean) for head in self.heads]


# ── 5. Roundtrip (Frobenius) loss ────────────────────────────────────────────
#
# Φ_} mandate: μ∘δ = id.  Here:
#   μ = compose_formula   (tuple → ZFC tokens)
#   δ = ZFCEncoder        (ZFC tokens → predicted tuple)
#
# L_frob = mean cross-entropy over 12 primitives between
#          predicted class and true class.
#
# The per-primitive contribution exposes which primitives are non-transmissible.

def frobenius_loss(
    logits_list: List[torch.Tensor],   # 12 tensors (B, num_values[i])
    targets:     torch.Tensor,         # (B, 12) integer targets
) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Returns:
        total_loss: scalar mean cross-entropy
        per_prim:   (12,) tensor of per-primitive losses (for probe analysis)
    """
    losses = []
    for i, logits in enumerate(logits_list):
        ce = F.cross_entropy(logits, targets[:, i])
        losses.append(ce)
    per_prim = torch.stack(losses)
    return per_prim.mean(), per_prim


