    tr.add_argument("--catalog",    type=str,   default=None,
                    help="catalog file or glob (default: syncon_catalog*.json)")
    tr.add_argument("--save",       type=str,   default="zfc_encoder.pt")

    # probe
    pr = sub.add_parser("probe")
    pr.add_argument("--model",      type=str,   default="zfc_encoder.pt")
    pr.add_argument("--catalog",    type=str,   default=None,
                    help="catalog file or glob (default: syncon_catalog*.json)")
    pr.add_argument("--top",        type=int,   default=20)
    pr.add_argument("--hidden",     type=int,   default=256)
    pr.add_argument("--layers",     type=int,   default=4)

    # iug — specific probe for IUG, grammar, ZFC
    ig = sub.add_parser("iug")
    ig.add_argument("--model",      type=str,   default="zfc_encoder.pt")
    ig.add_argument("--hidden",     type=int,   default=256)
    ig.add_argument("--layers",     type=int,   default=4)

    # entry — full formula display + roundtrip for a single named entry
    en = sub.add_parser("entry")
    en.add_argument("name",          type=str,
                    help="catalog entry name, or: iug / grammar / zfc")
    en.add_argument("--model",       type=str,   default="zfc_encoder.pt")
    en.add_argument("--catalog",     type=str,   default=None,
                    help="catalog file or glob (default: syncon_catalog*.json)")
    en.add_argument("--hidden",      type=int,   default=256)
    en.add_argument("--layers",      type=int,   default=4)
    en.add_argument("--no-model",    action="store_true",
                    help="skip roundtrip — show formula only")

    # recover — probe + specialist router
    rc = sub.add_parser("recover")
    rc.add_argument("--model",      type=str,   default="zfc_encoder.pt")
    rc.add_argument("--catalog",    type=str,   default=None,
                    help="catalog file or glob (default: syncon_catalog*.json)")
    rc.add_argument("--top",        type=int,   default=20)
    rc.add_argument("--hidden",     type=int,   default=256)
    rc.add_argument("--layers",     type=int,   default=4)

    # verify-recovery — backbone-independent structural proof
    vr = sub.add_parser("verify-recovery")
    vr.add_argument("--model",      type=str,   default="zfc_encoder.pt")
    vr.add_argument("--hidden",     type=int,   default=256)
    vr.add_argument("--layers",     type=int,   default=4)

    # stats
    st = sub.add_parser("stats")
    st.add_argument("--catalog",    type=str,   default=None,
                    help="catalog file or glob (default: syncon_catalog*.json)")

    args = parser.parse_args()

    if args.cmd == "train":
        train(
            catalog_path = args.catalog,
            n_epochs     = args.epochs,
            batch_size   = args.batch,
            lr           = args.lr,
            hidden_dim   = args.hidden,
            n_layers     = args.layers,
            save_path    = args.save,
        )
    elif args.cmd == "probe":
        run_probe(
            catalog_path = args.catalog,
            model_path   = args.model,
            top_n        = args.top,
            hidden_dim   = args.hidden,
            n_layers     = args.layers,
        )
    elif args.cmd == "iug":
        probe_specific(
            model_path = args.model,
            hidden_dim = args.hidden,
            n_layers   = args.layers,
        )
    elif args.cmd == "entry":
        probe_entry(
            name         = args.name,
            model_path   = args.model,
            catalog_path = args.catalog,
            hidden_dim   = args.hidden,
            n_layers     = args.layers,
            no_model     = args.no_model,
        )
    elif args.cmd == "verify-recovery":
        verify_recovery(
            model_path = args.model,
            hidden_dim = args.hidden,
            n_layers   = args.layers,
        )
    elif args.cmd == "recover":
        run_probe_with_recovery(
            catalog_path = args.catalog,
            model_path   = args.model,
            top_n        = args.top,
            hidden_dim   = args.hidden,
            n_layers     = args.layers,
        )
    elif args.cmd == "stats":
        formula_stats(args.catalog)
    else:
        parser.print_help()
        print("\nQuick start:")
        print("  uv run zfc_navigator.py stats             # check formula lengths")
        print("  uv run zfc_navigator.py train             # train encoder (300 epochs)")
        print("  uv run zfc_navigator.py probe --top 30   # transmissibility map")
        print("  uv run zfc_navigator.py recover --top 30 # probe + specialist recovery")
        print("  uv run zfc_navigator.py iug               # IUG / grammar / ZFC probe")
        print("  uv run zfc_navigator.py entry <name>      # full formula + roundtrip for one entry")
        print("  uv run zfc_navigator.py entry <name> --no-model  # formula only, no model needed")
