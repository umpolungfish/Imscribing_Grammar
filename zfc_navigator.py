def _normalize_entry(entry: dict) -> dict:
    """Translate non-canonical primitive values to canonical ones in-place copy."""
    out = dict(entry)
    for prim, aliases in _PRIM_ALIASES.items():
        if prim in out and out[prim] in aliases:
            out[prim] = aliases[out[prim]]
    return out


def tuple_to_indices(entry: dict) -> List[int]:
    """Map a catalog entry to a list of integer ordinal indices (one per primitive)."""
    return [int(ORDINALS[p][entry[p]]) for p in PRIMITIVES]


def indices_to_tuple(indices: List[int]) -> dict:
    """Recover a tuple dict from integer ordinal indices."""
    return {p: INV_ORDINALS[p][indices[i]] for i, p in enumerate(PRIMITIVES)}


def tuple_distance(a: dict, b: dict) -> float:
    """Weighted Euclidean distance between two tuples."""
    total = 0.0
    for p in PRIMITIVES:
        oa = ORDINALS[p][a[p]]
        ob = ORDINALS[p][b[p]]
        total += WEIGHTS[p] * (oa - ob) ** 2
    return math.sqrt(total)


