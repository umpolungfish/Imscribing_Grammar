def _workflows(domain: str) -> str:
    """Hand-written worked chains, kept out of the generated manifest.

    TOOL_MANIFEST_* is regenerated by gen_tool_manifest.py and anything written
    into it is lost on the next run, so composition guidance lives here instead.
    A domain without a workflows file simply contributes nothing.
    """
    path = _HERE / f"WORKFLOWS_{domain}.md"
    return path.read_text().rstrip() if path.exists() else ""

